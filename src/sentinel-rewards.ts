// Published SAFE reward allocations of Sentinel addresses, from github.com/safe-fndn/safenet-data
// (assets/rewards). Each published version of assets/rewards/latest.json is one Merkle root of the
// Ethereum distributor (REWARDS_DISTRIBUTOR in src/safenet.ts), and assets/rewards/proofs holds one
// file per address with its cumulative SAFE amount under that root.
//
// The files publish one cumulative amount per address and do not say which part is a Sentinel
// subsidy and which a staking reward. A Sentinel address that also stakes therefore cannot be
// split, and the dashboard says so. Nothing is computed here: only published amounts are copied.
//
// `npm run sync:sentinel-rewards [-- --ref <commit>]` refreshes dune/data/sentinel-rewards.json
// and regenerates the safenet_sentinel_rewards query.

import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { DEFAULT_ROOT } from "./config.ts";

export const REWARDS_SOURCE = "safe-fndn/safenet-data";
export const REWARDS_INDEX = "assets/rewards/latest.json";

// Proof files are sharded by the first eight hex digits of the lowercase address.
export const proofPath = (address: string) => {
  const a = address.toLowerCase().slice(2);
  return `assets/rewards/proofs/${a.slice(0, 2)}/${a.slice(2, 4)}/${a.slice(4, 6)}/${a.slice(6, 8)}/0x${a}.json`;
};

// One published root: the commit that published it, the end of the rewards it covers, and the root.
export type RewardRoot = { commit: string; published_at: string; rewards_until: string; merkle_root: string };
// One Sentinel address under one root. Amounts are SAFE base units (18 decimals), as strings.
export type RewardEntry = { address: string; merkle_root: string; cumulative_amount: string; kyc_amount: string };

export type SentinelRewardData = {
  source: string;
  ref: string;
  addresses: string[]; // Sentinel addresses looked up: labels and every onchain SentinelScheduled
  roots: RewardRoot[]; // oldest first
  entries: RewardEntry[];
};

const sqlString = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function sentinelRewardsSql(data: SentinelRewardData): string {
  const roots = data.roots.map(
    (r, i) =>
      `    ('root', ${i + 1}, ${r.merkle_root}, timestamp ${sqlString(r.rewards_until.replace("T", " ").replace(/\.\d+Z$|Z$/, ""))}, ${sqlString(r.commit)}, cast(null as varbinary), cast(null as uint256), cast(null as uint256))`,
  );
  const entries = data.entries.map((e) => {
    const root = data.roots.find((r) => r.merkle_root === e.merkle_root)!;
    return `    ('entry', ${data.roots.indexOf(root) + 1}, ${e.merkle_root}, timestamp ${sqlString(root.rewards_until.replace("T", " ").replace(/\.\d+Z$|Z$/, ""))}, ${sqlString(root.commit)}, ${e.address}, cast(${sqlString(e.cumulative_amount)} as uint256), cast(${sqlString(e.kyc_amount)} as uint256))`;
  });
  return `-- Published SAFE reward allocations of Sentinel addresses. Generated by \`npm run sync:sentinel-rewards\`
-- from github.com/${data.source} at commit ${data.ref}; do not edit by hand. src/sentinel-rewards.ts
--
-- kind = 'root': every published Merkle root (rewards_until = end of the rewards it covers);
-- root_order is the publication order (1 = oldest).
-- kind = 'entry': a Sentinel address with a proof under that root; cumulative_amount is the total
-- SAFE (base units, 18 decimals) claimable by the address under the root, all reward types
-- together, as published. No row for an address means nothing was published for it.
-- Addresses looked up: ${data.addresses.length} (labels and every onchain SentinelScheduled).

select kind, root_order, merkle_root, rewards_until, source_commit, address, cumulative_amount, kyc_amount
from (
    values
${[...roots, ...entries].join(",\n")}
) as t (kind, root_order, merkle_root, rewards_until, source_commit, address, cumulative_amount, kyc_amount)
`;
}

export const SENTINEL_REWARDS_PATH = join(DEFAULT_ROOT, "data", "sentinel-rewards.json");
export const SENTINEL_REWARDS_SQL_PATH = join(DEFAULT_ROOT, "queries", "safenet_sentinel_rewards", "query.sql");

export async function loadSentinelRewards(path = SENTINEL_REWARDS_PATH): Promise<SentinelRewardData> {
  return JSON.parse(await readFile(path, "utf8")) as SentinelRewardData;
}
