// Known non-user traffic (docs/metrics/network-and-revenue.md#test-and-operational-traffic).
//
//   - test_uncovered_chain: requests for Safes on chains the Charter does not cover. A rule, applied
//     in SQL through covered_chain.
//   - operational: Safes listed in dune/data/known-traffic.json, such as Safenet's own Arbitrator
//     Safe. Their requests are real production checks; totals include them and dashboards show
//     them separately.
//
// Nothing here says where a request originated (for example Safe{Wallet}): Safenet records no
// origin, and the sponsor is only the account that paid the fee.
//
// `npm run sync:known-traffic` regenerates the safenet_known_traffic query from the JSON file.

import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { DEFAULT_ROOT } from "./config.ts";

export const TRAFFIC_CATEGORIES = ["operational", "test"] as const;
export type KnownSafe = { chain_id: number; address: string; category: (typeof TRAFFIC_CATEGORIES)[number]; label: string; source: string };

export const KNOWN_TRAFFIC_PATH = join(DEFAULT_ROOT, "data", "known-traffic.json");
export const KNOWN_TRAFFIC_SQL_PATH = join(DEFAULT_ROOT, "queries", "safenet_known_traffic", "query.sql");

export function validateKnownSafes(safes: KnownSafe[]): string[] {
  const problems: string[] = [];
  const seen = new Set<string>();
  for (const [i, s] of safes.entries()) {
    const where = `known-traffic.json safes[${i}]`;
    if (!Number.isInteger(s.chain_id) || s.chain_id <= 0) problems.push(`${where}: chain_id must be a positive integer`);
    if (!/^0x[0-9a-f]{40}$/.test(s.address)) problems.push(`${where}: address must be lowercase 0x + 40 hex`);
    if (!TRAFFIC_CATEGORIES.includes(s.category)) problems.push(`${where}: category must be one of ${TRAFFIC_CATEGORIES.join(", ")}`);
    if (!s.label?.trim() || !s.source?.trim()) problems.push(`${where}: label and source are required`);
    const key = `${s.chain_id}:${s.address}`;
    if (seen.has(key)) problems.push(`${where}: duplicate ${key}`);
    seen.add(key);
  }
  return problems;
}

const sqlString = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function knownTrafficSql(safes: KnownSafe[]): string {
  const rows = safes.length
    ? safes.map((s) => `    (${s.chain_id}, ${s.address}, ${sqlString(s.category)}, ${sqlString(s.label)})`).join(",\n")
    : "    (cast(null as bigint), cast(null as varbinary), cast(null as varchar), cast(null as varchar))";
  return `-- Safes with known non-user Safenet traffic. Generated by \`npm run sync:known-traffic\` from
-- dune/data/known-traffic.json, where every entry has its source; do not edit by hand.
-- Join on (safe_chain_id, safe_address). Requests for Safes outside the Charter's chains are test
-- traffic by rule (covered_chain = false) and are not listed here.

select safe_chain_id, safe_address, category, label
from (
    values
${rows}
) as t (safe_chain_id, safe_address, category, label)
where safe_address is not null
`;
}

export async function loadKnownSafes(path = KNOWN_TRAFFIC_PATH): Promise<KnownSafe[]> {
  return (JSON.parse(await readFile(path, "utf8")) as { safes: KnownSafe[] }).safes;
}

// Entry point for `npm run sync:known-traffic`.
if (import.meta.url === `file://${process.argv[1]}`) {
  const safes = await loadKnownSafes();
  const problems = validateKnownSafes(safes);
  if (problems.length) throw new Error(problems.join("\n"));
  await writeFile(KNOWN_TRAFFIC_SQL_PATH, knownTrafficSql(safes));
  console.log(`${safes.length} known Safes written to ${KNOWN_TRAFFIC_SQL_PATH}`);
}
