// Names of Safenet participants (Sentinels and validators) for display, from
// github.com/safe-fndn/safenet-data (assets/sentinel-info.json, assets/validator-info.json).
//
// These files are labels only. Being listed, or `is_active` in them, does not make an address a
// current participant: membership comes from onchain events (for example, the Rockaway validator
// left at epoch 33960 and Blockchain Capital is listed but not in the genesis group). Queries
// match addresses in lowercase and show the address itself for unknown participants.
//
// `npm run sync:participants [-- --ref <commit>]` refreshes dune/data/ and regenerates the
// safenet_participant_labels query.

import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { DEFAULT_ROOT } from "./config.ts";

export const PARTICIPANT_SOURCE = "safe-fndn/safenet-data";
export const PARTICIPANT_FILES = { sentinel: "assets/sentinel-info.json", validator: "assets/validator-info.json" } as const;
export type Role = keyof typeof PARTICIPANT_FILES;

// address: lowercase, for matching; source_address: as published (checksummed in the source).
export type Participant = { role: Role; address: string; source_address: string; label: string };

// dune/data/participants.json: the source commit and the normalized entries.
export type ParticipantData = { source: string; ref: string; participants: Participant[] };

const ADDRESS = /^0x[0-9a-fA-F]{40}$/;

// Normalizes one source file. Entries without a valid address are dropped; a missing label falls
// back to the address. Duplicate addresses keep the first label.
export function normalize(role: Role, entries: unknown): Participant[] {
  if (!Array.isArray(entries)) throw new Error(`${PARTICIPANT_FILES[role]}: expected an array`);
  const seen = new Set<string>();
  const out: Participant[] = [];
  for (const e of entries as { address?: unknown; label?: unknown }[]) {
    if (typeof e?.address !== "string" || !ADDRESS.test(e.address.trim())) continue;
    const source_address = e.address.trim();
    const address = source_address.toLowerCase();
    if (seen.has(address)) continue;
    seen.add(address);
    const label = typeof e.label === "string" && e.label.trim() ? e.label.trim() : address;
    out.push({ role, address, source_address, label });
  }
  return out.sort((a, b) => (a.address < b.address ? -1 : 1));
}

// Display name of an address: its label for the role, else the address.
export function labelFor(participants: Participant[], role: Role, address: string): string {
  const a = address.toLowerCase();
  return participants.find((p) => p.role === role && p.address === a)?.label ?? a;
}

const sqlString = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function participantLabelsSql(data: ParticipantData): string {
  const rows = data.participants.map(
    (p) => `    (${sqlString(p.role)}, ${p.address}, ${sqlString(p.source_address ?? p.address)}, ${sqlString(p.label)})`,
  );
  return `-- Display names of Safenet Sentinels and validators. Generated by \`npm run sync:participants\`
-- from github.com/${data.source} at commit ${data.ref}; do not edit by hand.
-- Labels only: a row here does not mean the address is a current participant. Membership comes
-- from onchain events. Join on address (varbinary) and fall back to the address when no row matches:
--   coalesce(l.label, '0x' || lower(to_hex(x.address)))
-- source_address is the address exactly as published in the source file.

select role, address, source_address, label
from (
    values
${rows.join(",\n")}
) as t (role, address, source_address, label)
`;
}

export const PARTICIPANTS_PATH = join(DEFAULT_ROOT, "data", "participants.json");
export const LABELS_SQL_PATH = join(DEFAULT_ROOT, "queries", "safenet_participant_labels", "query.sql");

export async function loadParticipants(path = PARTICIPANTS_PATH): Promise<ParticipantData> {
  return JSON.parse(await readFile(path, "utf8")) as ParticipantData;
}
